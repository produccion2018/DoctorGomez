export const MEDICAMENTOS: Medicamento[] = Object.entries(DATOS).flatMap(([grupo, filas]) =>
  filas.map((f) => {
    const [nombre = "", dosis = "", vias = "", marcas = ""] = f.split("|");
    return {
      nombre,
      grupo,
      dosis: dosis.split(";").map((x) => x.trim()).filter(Boolean),
      vias: vias.split(",").map((x) => V[x.trim()] ?? x.trim()).filter(Boolean),
      ...(marcas ? { marcas: marcas.split(",").map((x) => x.trim()) } : {}),
    };
  }),
);

const sinTilde = (s: string) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();

/** Busca por nombre genérico o marca: "furo" → Furosemida; "dolex" → Acetaminofén. Primero lo que empieza igual. */
export function buscarMedicamentos(q: string, max = 8): Medicamento[] {
  const t = sinTilde(q.trim());
  if (t.length < 2) return [];
  const empieza: Medicamento[] = [];
  const contiene: Medicamento[] = [];
  for (const m of MEDICAMENTOS) {
    const n = sinTilde(m.nombre);
    const marcas = (m.marcas ?? []).map(sinTilde);
    if (n.startsWith(t) || marcas.some((x) => x.startsWith(t))) empieza.push(m);
    else if (n.includes(t) || marcas.some((x) => x.includes(t))) contiene.push(m);
  }
  return [...empieza, ...contiene].slice(0, max);
}

export const medicamentoPorNombre = (n: string) => MEDICAMENTOS.find((m) => sinTilde(m.nombre) === sinTilde(n.trim()));
